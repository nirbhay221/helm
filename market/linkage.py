"""Infer fraud rings from shared identity signals, never from a label.

This is the real version of sybil detection. A real platform cannot see "these
accounts are one person"; it sees signals (device fingerprint, payment
instrument, IP block, signup time) and must infer coordination. We build the
standard shared-attribute graph: accounts are nodes, an edge joins two accounts
the model judges to be the same actor, and a connected component of that graph
is a candidate ring. Each ring is scored by its members' bad-order rate, how
tightly the model links them (cohesion), its size, and whether it signed up in a
burst.

Two things make this more than a hand-tuned rule. First, the edge is decided by
a fitted logistic LINK MODEL over pairwise features (shared device, shared
payment instrument, exact or same-block IP, shared email domain, signup
proximity), so the relative weight of each signal is learned, not asserted, and
a single weak signal like a shared gmail domain cannot link two accounts on its
own. Second, candidate pairs are generated by BLOCKING on shared identifiers
(the standard entity-resolution step), so the scan stays fast on large account
sets instead of scoring every pair.

Grounded in the fraud-ring and entity-resolution literature: model accounts as
nodes and shared attributes as edges, block to generate candidates, score links,
take connected components (Liu 2025, arXiv 2512.19061; and the standard
connected-components baseline). The inferred ring id then replaces the
ground-truth cluster label the payout hardening used to be handed.
"""
from __future__ import annotations

from dataclasses import dataclass, field

from .marketplace import Marketplace

# identifiers weighted by how strong a signal they are, used only by the
# fallback scorer when the fitted model cannot run.
ATTR_WEIGHT = {"device_id": 1.0, "payment_fp": 1.0, "ip_prefix": 0.6, "email_domain": 0.3}
LINK_THRESHOLD = 1.5                 # fallback: total shared-signal weight to join two accounts
LINK_PROB = 0.8                      # model: P(same actor) at or above this links two accounts
BURST_WINDOW = 7                     # signups this close together look coordinated


@dataclass
class Ring:
    id: str
    members: list = field(default_factory=list)      # account ids, sorted
    shared: dict = field(default_factory=dict)        # identifier -> shared value
    bad_rate: float = 0.0
    signup_window: int = 0                            # day-spread of the ring's signups
    burst: bool = False                               # signed up within BURST_WINDOW
    cohesion: float = 0.0                             # mean model link-probability within the ring
    risk: float = 0.0
    action: str = "watch"                             # suspend_ring | watch
    reason: str = ""


def _ip_block(v: str) -> str:
    return v.rsplit(".", 1)[0] if v else ""


def _pair_features(a, b) -> list:
    """Pairwise link features, each in [0, 1]. Order matches the trained model."""
    import math
    dev = 1.0 if (a.device_id and a.device_id == b.device_id) else 0.0
    pay = 1.0 if (getattr(a, "payment_fp", "") and a.payment_fp == getattr(b, "payment_fp", "")) else 0.0
    ia, ib = getattr(a, "ip_prefix", ""), getattr(b, "ip_prefix", "")
    exact_ip = 1.0 if (ia and ia == ib) else 0.0
    fuzzy_ip = 1.0 if (ia and ib and ia != ib and _ip_block(ia) == _ip_block(ib)) else 0.0
    email = 1.0 if (getattr(a, "email_domain", "") and a.email_domain == getattr(b, "email_domain", "")) else 0.0
    da, db = getattr(a, "joined_day", 0), getattr(b, "joined_day", 0)
    prox = math.exp(-abs(da - db) / float(BURST_WINDOW))      # 1 same day, decays over a week
    return [dev, pay, exact_ip, fuzzy_ip, email, prox]


_LINK_MODEL = None


def _link_model():
    """A logistic link model fit once to synthetic account pairs. Positives are
    pairs of the same actor (who shares at least one strong identifier, and often
    corroborating weak ones); negatives are unrelated accounts that may still share
    a gmail domain, an ISP IP block, or a signup day by coincidence. The model
    learns that strong identifiers link and weak ones only corroborate. Swapping in
    confirmed-fraud pairs later means changing only this function. Deterministic."""
    global _LINK_MODEL
    if _LINK_MODEL is not None:
        return _LINK_MODEL
    import numpy as np
    from marketplace.models import LogisticModel
    rng = np.random.default_rng(7)
    X, y = [], []
    for _ in range(8000):
        # features are sampled independently; email and signup proximity occur just
        # as often in unrelated accounts, so they cannot carry a link on their own.
        dev = 1.0 if rng.random() < 0.15 else 0.0
        pay = 1.0 if rng.random() < 0.15 else 0.0
        exact_ip = 1.0 if rng.random() < 0.12 else 0.0
        fuzzy_ip = 1.0 if rng.random() < 0.15 else 0.0
        email = 1.0 if rng.random() < 0.40 else 0.0            # shared gmail is common
        prox = float(rng.uniform(0.0, 1.0))
        # ground truth: a strong identifier links on its own; a same-block IP links
        # only with corroboration; email or proximity alone never does.
        strong = dev or pay or exact_ip
        medium = fuzzy_ip
        corroborated = email or prox > 0.6
        same = bool(strong or (medium and corroborated))
        p = 0.95 if same else 0.04                             # small label noise
        label = 1.0 if rng.random() < p else 0.0
        X.append([dev, pay, exact_ip, fuzzy_ip, email, prox])
        y.append(label)
    _LINK_MODEL = LogisticModel(l2=0.5, lr=0.3, iters=5000).fit(X, y)
    return _LINK_MODEL


class LinkageEngine:
    def __init__(self, link_threshold: float = LINK_THRESHOLD, min_ring: int = 2,
                 suspend_risk: float = 0.5, burst_window: int = BURST_WINDOW,
                 link_prob: float = LINK_PROB, use_model: bool = True) -> None:
        self.link_threshold = link_threshold
        self.min_ring = min_ring
        self.suspend_risk = suspend_risk
        self.burst_window = burst_window
        self.link_prob = link_prob
        self.use_model = use_model

    @staticmethod
    def _link_weight(a, b) -> tuple[float, dict]:
        """Fallback scorer: additive shared-signal weight (no model)."""
        weight, shared = 0.0, {}
        for attr, w in ATTR_WEIGHT.items():
            va, vb = getattr(a, attr, ""), getattr(b, attr, "")
            if va and va == vb:
                weight += w
                shared[attr] = va
        ia, ib = getattr(a, "ip_prefix", ""), getattr(b, "ip_prefix", "")
        if ia and ib and ia != ib and _ip_block(ia) == _ip_block(ib):
            weight += 0.3
        return weight, shared

    def _linker(self):
        """Return a function (a, b) -> (linked: bool, prob: float). Uses the fitted
        model when possible, else the additive-weight fallback."""
        if self.use_model:
            try:
                model = _link_model()
                thr = self.link_prob
                def score(a, b):
                    p = model.predict_proba(_pair_features(a, b))
                    return p >= thr, p
                return score
            except Exception:
                pass
        thr = self.link_threshold
        def score(a, b):
            w, _ = self._link_weight(a, b)
            return w >= thr, min(1.0, w / 2.0)
        return score

    @staticmethod
    def _candidate_pairs(accs) -> set:
        """Blocking: only pairs that share at least one identifier (or IP block) are
        worth scoring. Standard entity-resolution step; keeps the scan near-linear."""
        # Block on strong identifiers and the IP block only. Email domain is too
        # common (half the accounts share one) to be a useful blocking key, and a
        # shared domain alone never links, so it would only add noise pairs.
        pairs = set()
        index: dict = {}
        for a in accs:
            for attr in ("device_id", "payment_fp", "ip_prefix"):
                v = getattr(a, attr, "")
                if v:
                    index.setdefault((attr, v), []).append(a.id)
            ib = _ip_block(getattr(a, "ip_prefix", ""))
            if ib:
                index.setdefault(("ip_block", ib), []).append(a.id)
        for ids in index.values():
            ids = sorted(set(ids))
            for i in range(len(ids)):
                for j in range(i + 1, len(ids)):
                    pairs.add((ids[i], ids[j]))
        return pairs

    def infer(self, m: Marketplace) -> list[Ring]:
        accs = list(m.accounts.values())
        by_id = {a.id: a for a in accs}
        parent = {a.id: a.id for a in accs}

        def find(x):
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        def union(x, y):
            parent[find(x)] = find(y)

        score = self._linker()
        prob = {}
        for x, y in self._candidate_pairs(accs):
            linked, p = score(by_id[x], by_id[y])
            if linked:
                prob[(x, y)] = p
                union(x, y)

        groups: dict[str, list] = {}
        for a in accs:
            groups.setdefault(find(a.id), []).append(a.id)

        rings: list[Ring] = []
        for root, members in groups.items():
            if len(members) < self.min_ring:
                continue
            members = sorted(members)
            shared = {}
            for attr in ATTR_WEIGHT:
                vals = {getattr(by_id[x], attr, "") for x in members}
                if len(vals) == 1 and next(iter(vals)):
                    shared[attr] = next(iter(vals))
            bad = tot = 0
            for x in members:
                orders = m.orders_as_buyer(x) + m.orders_as_seller(x)
                tot += len(orders)
                bad += sum(1 for o in orders if o.status in ("returned", "charged_back"))
            rate = round(bad / tot, 3) if tot else 0.0
            days = [by_id[x].joined_day for x in members]
            window = max(days) - min(days) if days else 0
            burst = window <= self.burst_window
            # cohesion: mean model link-probability over the ring's member pairs
            ps = [prob[(a, b)] for i, a in enumerate(members) for b in members[i + 1:]
                  if (a, b) in prob]
            cohesion = round(sum(ps) / len(ps), 3) if ps else 0.0
            risk = round(min(1.0, 0.40 * rate + 0.25 * cohesion
                             + 0.15 * min(1.0, len(members) / 5.0)
                             + 0.20 * (1.0 if burst else 0.0)), 3)
            action = "suspend_ring" if risk >= self.suspend_risk else "watch"
            reason = (f"{len(members)} accounts the link model ties together (cohesion {cohesion}), "
                      f"sharing {sorted(shared) or 'rotated identifiers'}"
                      f"{', signed up within ' + str(window) + ' days' if burst else ''} "
                      f"(bad-order rate {int(rate * 100)}%); inferred one coordinated actor. "
                      f"Risk {risk}. Action: {action}.")
            rings.append(Ring(id=f"ring-{root}", members=members, shared=shared,
                              bad_rate=rate, signup_window=window, burst=burst,
                              cohesion=cohesion, risk=risk, action=action, reason=reason))
        rings.sort(key=lambda r: r.risk, reverse=True)
        return rings

    def cluster_of(self, m: Marketplace) -> dict:
        """Map each account to its inferred ring id (or its own id if unlinked),
        so the payout hardening merges identities it INFERRED, not ones it was told."""
        label = {aid: aid for aid in m.accounts}
        for r in self.infer(m):
            for x in r.members:
                label[x] = r.id
        return label
