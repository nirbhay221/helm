"""The dashboard's data: the agent compiling policies and allocating globally.

Loads the precomputed policy scenarios (ui/scenarios_data.json, generated by
scripts/gen_scenarios.py with the live model) plus the creator population
rollup, and the payout-engine panel. Deterministic and keyless, so the page
needs no network at startup while still showing what the real model compiled.
Regenerate the scenarios with scripts/gen_scenarios.py.
"""
from __future__ import annotations

import functools
import json
import os

from arms.payout_engine import Contribution, Party, run_payout_engine
from paypal import Ledger, PayPalClient

CONTEXT = {"market_size_b": 314, "creators_m": 207, "late_pct": 87}
_SCENARIOS_FILE = os.path.join(os.path.dirname(__file__), "scenarios_data.json")
_REINVEST_FILE = os.path.join(os.path.dirname(__file__), "reinvest_data.json")
_DIRECTORY_FILE = os.path.join(os.path.dirname(__file__), "directory_data.json")


def _payout_engine_panel() -> dict:
    client, ledger = PayPalClient(env={"DEMO_MODE": "1"}), Ledger()
    pe = run_payout_engine(
        1000.0,
        [Contribution("Ava", {"c1", "c2", "c3", "c4"}), Contribution("Ben", {"c3", "c4", "c5"}),
         Contribution("Cy", {"c5", "c6"})],
        [Party("Ava", 400), Party("Ben", 300), Party("Cy", 150)],
        Party("Sybil", 1500, verified_activity=120, cluster="Sybil", honest=False),
        {"Ava": {"email": "ava@ex.com", "country": "US"}, "Ben": {"email": "ben@ex.com", "country": "IN"},
         "Cy": {"email": "cy@ex.com", "country": "BR"}, "Sybil": {"email": "z@ex.com", "country": "US"}},
        client, ledger, sender_batch_id="dash-payengine", purpose="COMMISSION",
        fail_items=set(), approved=True)
    return {
        "bulwark": {"naive_cheater_take": pe.bulwark.naive_cheater_take,
                    "hardened_cheater_take": pe.bulwark.hardened_cheater_take,
                    "honest_share": pe.bulwark.honest_cheater_share,
                    "hardening_applied": pe.bulwark.hardening_applied, "defeated": pe.bulwark.defeated},
        "clearwright_ok": pe.clearwright.ok,
        "tollgate": {"gross": pe.tollgate.total_gross, "withheld": pe.tollgate.total_withheld,
                     "net": pe.tollgate.total_net},
        "keystone": {"status": pe.keystone.status, "batch_id": pe.keystone.batch_id,
                     "conserved": pe.keystone.conserved}}


def _load_scenarios() -> dict:
    with open(_SCENARIOS_FILE, encoding="utf-8") as f:
        return json.load(f)


def _load_json(path: str) -> dict:
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def build_dashboard_data() -> dict:
    sc = _load_scenarios()
    pop = sc["population"]
    directory = _load_json(_DIRECTORY_FILE)
    return {
        "context": CONTEXT,
        "population": pop,
        "scenarios": sc["scenarios"],
        "reinvest": _load_json(_REINVEST_FILE),
        "directory": directory,
        "payout_engine": _payout_engine_panel(),
        "headline": {
            "creators": directory["total"],
            "total_owed": pop["total_owed"],
            "budget": pop["budget"],
            "countries": len(pop["by_country"]),
        },
    }


@functools.lru_cache(maxsize=1)
def dashboard_data_cached() -> dict:
    """The dashboard payload, computed once and reused; deterministic."""
    return build_dashboard_data()
